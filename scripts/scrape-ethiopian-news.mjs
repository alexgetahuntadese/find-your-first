import { mkdir, writeFile } from "node:fs/promises";

const OUTPUT = new URL("../src/data/news.ts", import.meta.url);
const SOURCES = [
  { name: "Fana Media", url: "https://www.fanamc.com/feed/" },
  { name: "FBC English", url: "https://www.fanabc.com/english/feed/" },
];

function decode(value) {
  return String(value || "")
    .replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, "$1")
    .replace(/<[^>]+>/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&#x27;/gi, "'")
    .replace(/&#(\d+);/g, (_, code) => String.fromCharCode(Number(code)))
    .replace(/\s+/g, " ")
    .trim();
}

function tag(item, name) {
  const match = item.match(new RegExp(`<${name}(?:\\s[^>]*)?>([\\s\\S]*?)</${name}>`, "i"));
  return decode(match?.[1]);
}

function escape(value) {
  return JSON.stringify(String(value || ""));
}

const all = [];
for (const source of SOURCES) {
  try {
    const response = await fetch(source.url, { headers: { "User-Agent": "SERATEGNA-news-indexer/1.0 (+https://serategna.com.et/)" } });
    if (!response.ok) continue;
    const xml = await response.text();
    const items = [...xml.matchAll(/<item(?:\s[^>]*)?>([\s\S]*?)<\/item>/gi)].map((match) => match[1]);
    for (const item of items.slice(0, 12)) {
      const title = tag(item, "title");
      const summary = tag(item, "description") || tag(item, "content:encoded");
      const publishedAt = tag(item, "pubDate") || tag(item, "dc:date");
      if (title) all.push({ title, summary: summary.slice(0, 260), source: source.name, publishedAt });
    }
  } catch (error) {
    console.warn(`Could not refresh ${source.name}: ${error.message}`);
  }
}

const unique = [...new Map(all.map((item) => [item.title.toLowerCase(), item])).values()]
  .sort((a, b) => (Date.parse(b.publishedAt) || 0) - (Date.parse(a.publishedAt) || 0))
  .slice(0, 12);

const source = `// Generated by scripts/scrape-ethiopian-news.mjs. Refresh with npm run scrape:news.\nexport type NewsItem = { title: string; summary: string; source: string; publishedAt: string };\n\nexport const latestNews: NewsItem[] = ${JSON.stringify(unique, null, 2)};\n`;
await mkdir(new URL("../src/data/", import.meta.url), { recursive: true });
await writeFile(OUTPUT, source);
console.log(`Saved ${unique.length} Ethiopia news items to ${OUTPUT.pathname}`);
